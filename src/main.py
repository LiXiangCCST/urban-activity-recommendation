def validate_nyc_raw_data(config: dict[str, Any], output_dir: str | Path) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    raw_paths = config["nyc"].get("raw_paths", {})
    dataset_to_path = {
        "facilities": raw_paths.get("facilities"),
        "schools": raw_paths.get("schools"),
        "hospitals": raw_paths.get("hospitals"),
        "parks": raw_paths.get("parks"),
        "libraries": raw_paths.get("libraries"),
        "grocery": raw_paths.get("grocery"),
        "employment": raw_paths.get("employment"),
        "leisure": raw_paths.get("leisure"),
        "census_areas": raw_paths.get("census_areas") or raw_paths.get("candidate_areas"),
        "housing_cost": raw_paths.get("housing_cost"),
        "risk": raw_paths.get("risk"),
        "transit_stops": raw_paths.get("transit_stops"),
    }
    results = []
    for dataset_type in SUPPORTED_DATASET_TYPES:
        path = dataset_to_path.get(dataset_type)
        if not path:
            results.append({"dataset_type": dataset_type, "path": None, "exists": False, "valid": False, "row_count": None, "missing_required_columns": [], "missing_optional_columns": [], "invalid_numeric_columns": [], "invalid_coordinate_rows": [], "messages": ["No configured path."]})
            continue
        results.append(validate_nyc_raw_file(path, dataset_type))

    summary = summarize_validation_results(results)
    output_path = Path(output_dir)
    output_path.mkdir(parents=True, exist_ok=True)
    report_df = validation_results_to_dataframe(results)
    report_df.to_csv(output_path / "nyc_data_validation_report.csv", index=False)
    with (output_path / "nyc_data_validation_report.json").open("w", encoding="utf-8") as file:
        json.dump({"summary": summary, "results": results}, file, indent=2)

    print("NYC raw data validation")
    print(f"Report CSV: {output_path / 'nyc_data_validation_report.csv'}")
    print(f"Report JSON: {output_path / 'nyc_data_validation_report.json'}")
    print(f"Existing files: {summary['existing_files']} | Valid: {summary['valid_files']} | Invalid: {summary['invalid_files']} | Missing optional: {summary['missing_files']}")
    for result in results:
        status = "valid" if result.get("exists") and result.get("valid") else "missing" if not result.get("exists") else "invalid"
        print(f"- {result['dataset_type']}: {status} ({result.get('path')})")
        if result.get("exists") and not result.get("valid"):
            print(f"  {' | '.join(result.get('messages', []))}")
    return results, summary


def _score_recommendation(
    method_result: dict,
    profile,
    areas: pd.DataFrame,
    resources: pd.DataFrame,
    travel_times: pd.DataFrame,
    config: dict[str, Any],
) -> dict:
    reward = compute_reward(
        method_result["area_id"],
        profile,
        areas,
        resources,
        travel_times,
        config["sample_data"]["theta_by_category"],
        config["reward_weights"],
    )
    return {
        "profile_id": profile.profile_id,
        "method": method_result["method"],
        "area_id": method_result["area_id"],
        "method_score": method_result["score"],
        "reward": reward["reward"],
        "accessibility": reward["accessibility"],
        "coverage_15_min": activity_coverage_within_15(profile, method_result["area_id"], travel_times),
        "explanation": method_result["explanation"],
    }


def _load_synthetic_dataset(config: dict[str, Any], generate_sample: bool = False) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, dict[str, Any]]:
    sample_dir = config.get("paths", {}).get("synthetic_sample", "data/sample")
    if generate_sample or not sample_data_exists(sample_dir):
        generate_sample_data(output_dir=sample_dir)
    areas, resources, travel_times = load_sample_data(sample_dir)
    return areas, resources, travel_times, {"data_mode": "synthetic", "case_city": config.get("case_city", "Synthetic City"), "nyc_data_variant": "none", "data_provenance": "synthetic", "messages": ["Loaded synthetic sample data."]}


def _load_nyc_example_dataset(config, no_fallback=False, max_areas=None, max_resources=None, output_dir=None):
    try:
        processed = process_nyc_data(config, max_areas=max_areas, max_resources=max_resources, summary_output_dir=output_dir)
        metadata = metadata_with_provenance({"data_mode": "nyc", **processed["metadata"]}, "example_minimal", "fictional_minimal")
        metadata.setdefault("messages", []).append("Using fictional minimal NYC-like data for pipeline validation.")
        return processed["areas"], processed["resources"], processed["travel_times"], metadata
    except Exception as exc:
        message = f"NYC example pipeline could not produce a complete dataset: {exc}"
        if no_fallback:
            raise NYCDataUnavailable(message) from exc
        print(message)
        print("Falling back to synthetic sample data. Use --no-fallback to fail instead.")
        areas, resources, travel_times, metadata = _load_synthetic_dataset(config)
        metadata["fallback_reason"] = message
        return areas, resources, travel_times, metadata


def _load_nyc_real_dataset(config, no_fallback=False, max_areas=None, max_resources=None, output_dir=None):
    raw_dir = config.get("paths", {}).get("nyc_raw", "data/raw/nyc/real")
    try:
        processed = standardize_nyc_real_data(config, raw_dir=raw_dir, output_dir=output_dir or "outputs", max_areas=max_areas, max_resources=max_resources)
        return processed["areas"], processed["resources"], processed["travel_times"], processed["metadata"]
    except Exception as exc:
        message = f"Real NYC data pipeline could not produce a complete dataset: {exc}"
        if no_fallback:
            raise NYCDataUnavailable(message) from exc
        print(message)
        print("Falling back to synthetic sample data. Use --no-fallback to fail instead.")
        areas, resources, travel_times, metadata = _load_synthetic_dataset(config)
        metadata["fallback_reason"] = message
        return areas, resources, travel_times, metadata


def _load_nyc_dataset(config, variant="example_minimal", no_fallback=False, max_areas=None, max_resources=None, output_dir=None):
    if variant == "real":
        return _load_nyc_real_dataset(config, no_fallback=no_fallback, max_areas=max_areas, max_resources=max_resources, output_dir=output_dir)
    if variant == "example_minimal":
        return _load_nyc_example_dataset(config, no_fallback=no_fallback, max_areas=max_areas, max_resources=max_resources, output_dir=output_dir)
    if variant == "auto":
        real_config = apply_nyc_raw_dir(config, "data/raw/nyc/real")
        try:
            return _load_nyc_real_dataset(real_config, no_fallback=True, max_areas=max_areas, max_resources=max_resources, output_dir=output_dir)
        except Exception as exc:
            if no_fallback:
                raise
            print(f"Auto variant could not use real NYC data: {exc}")
            if output_dir:
                quality_path = Path(output_dir) / "real_nyc_data_quality_report.md"
                Path(output_dir).mkdir(parents=True, exist_ok=True)
                quality_path.write_text("# Real NYC data quality report\n\n- Run provenance: fictional_minimal or synthetic fallback\n- Real NYC data status: unavailable\n- Limitation: no usable real public resource files were found, so auto mode fell back.\n")
            example_config = apply_nyc_raw_dir(config, "data/raw/nyc/example_minimal")
            try:
                return _load_nyc_example_dataset(example_config, no_fallback=True, max_areas=max_areas, max_resources=max_resources, output_dir=output_dir)
            except Exception as example_exc:
                print(f"Auto variant could not use example_minimal data: {example_exc}")
                areas, resources, travel_times, metadata = _load_synthetic_dataset(config)
                metadata["fallback_reason"] = f"auto real failed: {exc}; example failed: {example_exc}"
                return areas, resources, travel_times, metadata
    raise ValueError(f"Unsupported NYC data variant: {variant}")


def load_dataset_for_mode(args: argparse.Namespace, config: dict[str, Any], output_dir: str | Path | None = None) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, dict[str, Any]]:
    data_mode = args.data_mode or config.get("data_mode", "synthetic")
    if data_mode == "synthetic":
        return _load_synthetic_dataset(config, generate_sample=args.generate_sample)
    if data_mode == "nyc":
        return _load_nyc_dataset(config, variant=args.nyc_data_variant, no_fallback=args.no_fallback, max_areas=args.max_areas, max_resources=args.max_resources, output_dir=output_dir)
    raise ValueError(f"Unsupported data mode: {data_mode}")


def build_experiment_comparison(recommendations: pd.DataFrame, rl_results: pd.DataFrame) -> pd.DataFrame:
    rows = []
    methods = ["weighted_score", "nearest_resource", "fifteen_minute_city", "cost_first"]
    for profile_id in sorted(recommendations["profile_id"].unique()):
        profile_rows = recommendations[recommendations["profile_id"] == profile_id]
        row: dict[str, Any] = {"profile_id": profile_id}
        for method in methods:
            method_rows = profile_rows[profile_rows["method"] == method]
            if method_rows.empty:
                continue
            item = method_rows.iloc[0]
            prefix = method.replace("fifteen_minute_city", "fifteen_minute").replace("nearest_resource", "nearest_resource")
            row[f"{prefix}_area"] = item["area_id"]
            row[f"{prefix}_reward"] = item["reward"]
            row[f"{prefix}_accessibility"] = item["accessibility"]
        rl_row = rl_results[rl_results["profile_id"] == profile_id]
        if not rl_row.empty:
            row["rl_selected_area"] = rl_row.iloc[0]["selected_area"]
            row["rl_final_reward"] = rl_row.iloc[0]["final_reward"]
            row["rl_final_accessibility"] = rl_row.iloc[0]["final_accessibility"]
        rows.append(row)
    return pd.DataFrame(rows)


def dataframe_to_markdown(df: pd.DataFrame) -> str:
    if df.empty:
        return "(no rows)"
    columns = list(df.columns)
    lines = ["| " + " | ".join(columns) + " |", "| " + " | ".join(["---"] * len(columns)) + " |"]
    for _, row in df.iterrows():
        values = [str(row[column]) for column in columns]
        lines.append("| " + " | ".join(values) + " |")
    return "\n".join(lines)


def write_run_summary(
    output_path: Path,
    metadata: dict[str, Any] | None,
    areas: pd.DataFrame,
    resources: pd.DataFrame,
    graph,
    recommendations: pd.DataFrame,
    rl_results: pd.DataFrame,
    generated_files: list[str],
) -> Path:
    weighted = recommendations[recommendations["method"] == "weighted_score"]
    lines = [
        "# Run summary",
        "",
        f"- Data mode: {metadata.get('data_mode', 'unknown') if metadata else 'unknown'}",
        f"- NYC data variant: {metadata.get('nyc_data_variant', 'none') if metadata else 'none'}",
        f"- Data provenance: {metadata.get('data_provenance', 'unknown') if metadata else 'unknown'}",
        f"- Case city: {metadata.get('case_city', 'N/A') if metadata else 'N/A'}",
        f"- Candidate areas: {len(areas)}",
        f"- Resources: {len(resources)}",
        f"- Graph nodes: {graph.number_of_nodes()}",
        f"- Graph edges: {graph.number_of_edges()}",
        f"- Profiles evaluated: {', '.join(sorted(recommendations['profile_id'].unique()))}",
        "",
        "## Top recommendation by profile",
        "",
    ]
    for _, row in weighted.sort_values("profile_id").iterrows():
        lines.append(f"- {row['profile_id']}: {row['area_id']} (reward={row['reward']:.3f}, accessibility={row['accessibility']:.3f})")
    lines.extend(["", "## Weighted-score baseline summary", ""])
    lines.append(dataframe_to_markdown(weighted[["profile_id", "area_id", "reward", "accessibility", "coverage_15_min"]]))
    lines.extend(["", "## RL environment demo summary", ""])
    lines.append(dataframe_to_markdown(rl_results))
    lines.extend(["", "## Output files generated", ""])
    for file_name in generated_files:
        lines.append(f"- {file_name}")
    provenance = metadata.get("data_provenance", "unknown") if metadata else "unknown"
    travel_source = metadata.get("travel_time_source", "unknown") if metadata else "unknown"
    limitation_lines = ["", "## Limitations", ""]
    if travel_source == "routed_matrix":
        limitation_lines.append("- NYC travel times were loaded from a precomputed routed matrix; routing assumptions still need documentation.")
    elif travel_source == "effective_multimodal":
        limitation_lines.append("- NYC travel times use the effective multimodal layer with walking, GTFS approximation, road fallback, and profile penalties; this is not full OpenTripPlanner routing.")
    else:
        limitation_lines.append("- NYC travel times are distance-based approximations, not routed OpenTripPlanner outputs.")
    if provenance == "fictional_minimal":
        limitation_lines.append("- Minimal example data is fictional and only exercises the pipeline.")
    elif provenance.startswith("partial_real"):
        limitation_lines.append("- This is a partial-real run; some public datasets are used, but placeholder, approximate, or missing inputs remain.")
    limitation_lines.extend(["- POI quality scores are defaults or source-provided proxies.", "- RL module remains a skeleton with a heuristic policy."])
    lines.extend(limitation_lines)
    path = output_path / "run_summary.md"
    path.write_text("\n".join(lines) + "\n")
    return path


def run_recommendation_workflow(
    areas: pd.DataFrame,
    resources: pd.DataFrame,
    travel_times: pd.DataFrame,
    config: dict[str, Any],
    output_dir: str | Path,
    metadata: dict[str, Any] | None = None,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    output_path = Path(output_dir)
    output_path.mkdir(parents=True, exist_ok=True)

    graph = build_urban_graph(areas, resources, travel_times)
    profiles = get_profiles()

    recommendation_rows = []
    reward_surface_rows = []
    rl_rows = []

    for profile in profiles.values():
        reward_surface = compute_rewards_for_all(
            profile,
            areas,
            resources,
            travel_times,
            config["sample_data"]["theta_by_category"],
            config["reward_weights"],
        )
        reward_surface["profile_id"] = profile.profile_id
        reward_surface_rows.extend(reward_surface.to_dict("records"))

        methods = [
            nearest_resource.recommend(profile, areas, resources, travel_times),
            fifteen_minute_city.recommend(
                profile,
                areas,
                resources,
                travel_times,
                threshold=config["baselines"]["fifteen_minute_threshold"],
            ),
            weighted_score.recommend(
                profile,
                areas,
                resources,
                travel_times,
                config["sample_data"]["theta_by_category"],
                config["reward_weights"],
            ),
            cost_first.recommend(profile, areas, resources, travel_times, config["sample_data"]["theta_by_category"]),
        ]
        for method_result in methods:
            recommendation_rows.append(
                _score_recommendation(method_result, profile, areas, resources, travel_times, config)
            )

        env = UrbanActivityRecommendationEnv(
            graph,
            profile,
            areas,
            resources,
            travel_times,
            config["sample_data"]["theta_by_category"],
            config["reward_weights"],
            max_steps=config["environment"]["max_steps"],
            start_area=config["environment"]["start_area"],
        )
        rl_rows.append(run_demo_episode(env, PPOAgent(policy="heuristic")))

    recommendations = recommendation_comparison_table(recommendation_rows)
    reward_surfaces = pd.DataFrame(reward_surface_rows)
    rl_results = pd.DataFrame(rl_rows)
    fairness = pd.DataFrame([fairness_summary(recommendations[recommendations["method"] == "weighted_score"])])
    comparison = build_experiment_comparison(recommendations, rl_results)

    generated_files = []
    for filename, df in [
        ("recommendations.csv", recommendations),
        ("reward_surfaces.csv", reward_surfaces),
        ("rl_demo_results.csv", rl_results),
        ("fairness_summary.csv", fairness),
        ("recommendation_comparison.csv", comparison),
    ]:
        df.to_csv(output_path / filename, index=False)
        generated_files.append(filename)
    if metadata:
        with (output_path / "run_metadata.yaml").open("w", encoding="utf-8") as file:
            yaml.safe_dump(metadata, file, sort_keys=False)
        generated_files.append("run_metadata.yaml")

    for plotter in [plot_recommended_area_by_profile, plot_baseline_comparison, plot_accessibility_comparison, plot_reward_comparison]:
        plot_path = plotter(recommendations, output_path)
        generated_files.append(plot_path.name)

    report_paths = generate_research_reports(output_path, recommendations, rl_results, areas, resources, travel_times, config, metadata)
    for report_path in report_paths:
        if report_path.is_relative_to(output_path):
            generated_files.append(str(report_path.relative_to(output_path)))
        else:
            generated_files.append(str(report_path))

    summary_path = write_run_summary(output_path, metadata, areas, resources, graph, recommendations, rl_results, generated_files)
    generated_files.append(summary_path.name)

    print("\nUrban Activity Area Recommendation Demo")
    if metadata:
        print(f"Data mode: {metadata.get('data_mode', 'unknown')} | Case city: {metadata.get('case_city', config.get('case_city', 'N/A'))}")
        for message in metadata.get("messages", []):
            print(f"- {message}")
    print(f"Areas: {len(areas)} | Resources: {len(resources)} | Graph nodes: {graph.number_of_nodes()} | Graph edges: {graph.number_of_edges()}")
    print("\nWeighted-score recommendations:")
    print(recommendations[recommendations["method"] == "weighted_score"][["profile_id", "area_id", "reward", "accessibility", "coverage_15_min"]].to_string(index=False))
    print("\nRL environment demo:")
    print(rl_results.to_string(index=False))
    print(f"\nOutputs saved to {output_path}/")

    return recommendations, rl_results


def run_demo(args: argparse.Namespace | None = None) -> tuple[pd.DataFrame, pd.DataFrame] | None:
    if args is None:
        args = parse_args()
    config = load_config()
    raw_dir = args.nyc_raw_dir
    if not raw_dir and args.data_mode == "nyc" and args.nyc_data_variant in {"example_minimal", "real"}:
        raw_dir = default_raw_dir_for_variant(args.nyc_data_variant)
    config = apply_nyc_raw_dir(config, raw_dir)
    if args.case_city:
        config["case_city"] = args.case_city
    output_dir = args.output_dir or config.get("paths", {}).get("outputs", "outputs")

    if args.download_nyc_data:
        raw_dir = args.nyc_raw_dir or "data/raw/nyc/real"
        report = download_nyc_public_data(raw_dir=raw_dir, output_dir=output_dir, dataset_id=args.dataset_id, skip_existing=args.skip_existing)
        print(f"NYC download report saved to {Path(output_dir) / 'nyc_download_report.json'}")
        print(f"Downloaded: {report['summary']['downloaded']} | Failed: {report['summary']['failed']} | Skipped: {report['summary']['skipped']}")
        return None
    if args.build_real_nyc_inputs:
        raw_dir = args.nyc_raw_dir or "data/raw/nyc/real"
        summary = build_real_nyc_inputs(raw_dir=raw_dir, output_dir=output_dir)
        print(f"Real NYC input build summary saved to {Path(output_dir) / 'step8_real_input_build_summary.json'}")
        for result in summary.get("results", []):
            print(f"- {result.get('file')}: {result.get('status')} ({result.get('rows', 0)} rows)")
        return None
    if args.build_step9_public_data:
        raw_dir = args.nyc_raw_dir or "data/raw/nyc/real"
        summary = build_step9_public_data(raw_dir=raw_dir, output_dir=output_dir)
        print(f"Step 9 public data build summary saved to {Path(output_dir) / 'step9_public_data_build_summary.json'}")
        for key in ["housing", "employment", "leisure"]:
            result = summary.get(key, {})
            print(f"- {key}: {result.get('status')} ({result.get('rows', result.get('nonzero_housing_rows', 0))} rows)")
        return None
    if args.print_nyc_template_info:
        print_nyc_template_info()
        return None
    if args.validate_data == "nyc":
        validate_nyc_raw_data(config, output_dir)
        return None

    areas, resources, travel_times, metadata = load_dataset_for_mode(args, config, output_dir=output_dir)
    if args.run_household_experiment:
        household_output_dir = args.household_output_dir or output_dir
        auto_step15 = "step15" in str(args.household_profiles).lower() or "step15" in str(household_output_dir).lower()
        run_household_experiment(
            areas,
            resources,
            travel_times,
            config,
            household_output_dir,
            household_profiles_path=args.household_profiles,
            household_members_path=args.household_members,
            metadata=metadata,
            housing_penalty_scenario="all" if auto_step15 else args.housing_penalty_scenario,
            sensitivity_run=args.household_sensitivity_run or auto_step15 or args.housing_penalty_scenario == "all",
        )
        return None
    return run_recommendation_workflow(areas, resources, travel_times, config, output_dir, metadata)


