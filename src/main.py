def apply_nyc_raw_dir(config: dict[str, Any], raw_dir: str | None) -> dict[str, Any]:
    if not raw_dir:
        return config
    base = Path(raw_dir)
    raw_paths = dict(config["nyc"].get("raw_paths", {}))
    raw_paths.update(
        {
            "candidate_areas": str(base / "census_areas.csv"),
            "census_areas": str(base / "census_areas.csv"),
            "acs_tracts": str(base / "acs_tracts.csv"),
            "facilities": str(base / "facilities.csv"),
            "schools": str(base / "schools.csv"),
            "hospitals": str(base / "hospitals.csv"),
            "parks": str(base / "parks.csv"),
            "libraries": str(base / "libraries.csv"),
            "grocery": str(base / "grocery.csv"),
            "employment": str(base / "employment.csv"),
            "leisure": str(base / "leisure.csv"),
            "housing_cost": str(base / "housing_cost.csv"),
            "risk": str(base / "risk.csv"),
            "transit_stops": str(base / "transit_stops.csv"),
            "gtfs_zip": str(base / "gtfs.zip"),
        }
    )
    config = dict(config)
    config["nyc"] = dict(config["nyc"])
    config["nyc"]["raw_paths"] = raw_paths
    config["paths"] = dict(config.get("paths", {}))
    config["paths"]["nyc_raw"] = str(base)
    return config


